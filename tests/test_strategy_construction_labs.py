"""Native acceptance of six Strategy/Construction source families."""
from dataclasses import FrozenInstanceError
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = {
    "PDP1-Strategy-Rulebook": 7,
    "PDP2-Factory-and-Builder-Config-Kit": 7,
    "PDP-05-pdp3-strategy-without-ceremony-supplemental-2": 5,
    "PDP-06-pdp3-strategy-without-ceremony-supplemental-3": 5,
    "PDP-07-pdp4-factory-and-builder-in-python-supplemental-2": 5,
    "PDP-08-pdp4-factory-and-builder-in-python-supplemental-3": 5,
}
OUTPUTS = [
    "standard: $49.50\nloyalty: $44.55\nbulk: $41.50\n",
    "# Weekly Status\n- Draft ready\n- Tests passed\n\nTag: `pythonic`\n\nGenerated by report exporter.\n",
    "doubled: 8\nbonus: 7\nrepeat: 7\n",
    "winner: bonus 9\nrules: ['double', 'bonus']\n",
    "base sections: 0\nPLAN\ndraft\nreviewed\n",
    "loaded: [ready]\n",
]


class StrategyConstructionAcceptance(unittest.TestCase):
    def contracts(self, folder, role):
        result = subprocess.run(
            [sys.executable, "-B", "-m", "unittest", "discover", "-s", ".",
             "-p", "test_contract.py", "-v"],
            cwd=ROOT / folder / role, capture_output=True, text=True, timeout=20)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn(f"Ran {FAMILIES[folder]} tests", result.stderr)

    def test_all_reference_contracts(self):
        for folder in FAMILIES:
            with self.subTest(folder=folder):
                self.contracts(folder, "solution")

    def test_two_working_refactor_baselines_already_pass_contracts(self):
        for folder in list(FAMILIES)[:2]:
            with self.subTest(folder=folder):
                self.contracts(folder, "starter")

    def test_exact_reference_driver_outputs(self):
        for folder, output in zip(FAMILIES, OUTPUTS):
            result = subprocess.run(
                [sys.executable, "-B", "main.py"], cwd=ROOT / folder / "solution",
                capture_output=True, text=True, timeout=10)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, output)
            self.assertEqual(result.stderr, "")

    def test_refactor_baseline_and_reference_have_same_driver_output(self):
        for folder, output in zip(list(FAMILIES)[:2], OUTPUTS[:2]):
            result = subprocess.run(
                [sys.executable, "-B", "main.py"], cwd=ROOT / folder / "starter",
                capture_output=True, text=True, timeout=10)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, output)

    def test_four_small_starters_announce_actual_declared_work(self):
        for folder in list(FAMILIES)[2:]:
            result = subprocess.run(
                [sys.executable, "-B", "main.py"], cwd=ROOT / folder / "starter",
                capture_output=True, text=True, timeout=10)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("starter unfinished:", result.stdout)
            self.assertIn("Complete ", result.stdout)

    def test_reference_pricing_configuration_boundaries(self):
        path = ROOT / "PDP1-Strategy-Rulebook/solution/main.py"
        spec = importlib.util.spec_from_file_location("pricing_reference", path)
        module = importlib.util.module_from_spec(spec)
        sys.modules["pricing_reference"] = module
        spec.loader.exec_module(module)
        cart = [module.LineItem("item", 10)]
        low, high = module.LoyaltyDiscount(0.2), module.LoyaltyDiscount(0.5)
        self.assertEqual([low(cart), high(cart), low(cart)], [8, 5, 8])
        with self.assertRaises(FrozenInstanceError):
            low.percent_off = 0.9
        for fraction in [-1, 1.1, float("nan")]:
            with self.assertRaises(ValueError):
                module.LoyaltyDiscount(fraction)
        with self.assertRaises(ValueError):
            module.BulkBasketDiscount(0, 1)
        with self.assertRaises(TypeError):
            module.BulkBasketDiscount(True, 1)
        with self.assertRaises(ValueError):
            module.BulkBasketDiscount(1, -1)


if __name__ == "__main__":
    unittest.main()
