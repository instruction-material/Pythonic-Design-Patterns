"""Build owned report snapshots and choose a callable exporter."""
from collections.abc import Callable
from dataclasses import dataclass, field

ReportExporter = Callable[["Report"], str]


def require_text(text: str) -> str:
    if not isinstance(text, str):
        raise TypeError("text must be a string")
    if not text.strip():
        raise ValueError("text must contain a non-space character")
    return text


@dataclass
class Report:
    title: str
    sections: list[str] = field(default_factory=list)
    include_footer: bool = False
    tag: str | None = None

    def __post_init__(self) -> None:
        validate_report(self)
        self.sections = list(self.sections)


def validate_report(report: Report) -> None:
    if not isinstance(report, Report):
        raise TypeError("report must be a Report")
    require_text(report.title)
    if not isinstance(report.sections, list):
        raise TypeError("sections must be a list")
    for section in report.sections:
        require_text(section)
    if not isinstance(report.include_footer, bool):
        raise TypeError("footer must be a boolean")
    if report.tag is not None:
        require_text(report.tag)


class ReportBuilder:
    def __init__(self, title: str) -> None:
        self._report = Report(title)

    def add_section(self, section: str) -> "ReportBuilder":
        self._report.sections.append(require_text(section))
        return self

    def tagged(self, tag: str) -> "ReportBuilder":
        self._report.tag = require_text(tag)
        return self

    def with_footer(self) -> "ReportBuilder":
        self._report.include_footer = True
        return self

    def build(self) -> Report:
        return Report(self._report.title, self._report.sections,
                      self._report.include_footer, self._report.tag)


def markdown_text(report: Report) -> str:
    validate_report(report)
    lines = [f"# {report.title}", *["- " + s for s in report.sections]]
    if report.tag is not None:
        lines.append("\nTag: `" + report.tag + "`")
    if report.include_footer:
        lines.append("\nGenerated by report exporter.")
    return "\n".join(lines)


def plain_text(report: Report) -> str:
    validate_report(report)
    lines = [report.title.upper(), *report.sections]
    if report.tag is not None:
        lines.append("[" + report.tag + "]")
    if report.include_footer:
        lines.append("-- generated by report exporter --")
    return "\n".join(lines)


class MarkdownExporter:
    def export(self, report: Report) -> str:
        return markdown_text(report)

    def __call__(self, report: Report) -> str:
        return self.export(report)


class TextExporter:
    def export(self, report: Report) -> str:
        return plain_text(report)

    def __call__(self, report: Report) -> str:
        return self.export(report)


def make_exporter(format_name: str) -> ReportExporter:
    if not isinstance(format_name, str):
        raise TypeError("format name must be a string")
    if format_name == "markdown":
        return MarkdownExporter()
    if format_name == "text":
        return TextExporter()
    raise ValueError("unknown format: " + format_name)


def build_sample_report() -> Report:
    return (ReportBuilder("Weekly Status").add_section("Draft ready")
            .add_section("Tests passed").tagged("pythonic").with_footer().build())


def main() -> None:
    report = build_sample_report()
    print(make_exporter("markdown")(report))


if __name__ == "__main__":
    main()
