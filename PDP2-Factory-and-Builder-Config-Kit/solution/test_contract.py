import unittest
from main import Report, ReportBuilder, make_exporter


class ReportContract(unittest.TestCase):
    def test_normal_formats_tag_and_footer(self):
        report = ReportBuilder("Plan").add_section("draft").tagged("tag").with_footer().build()
        self.assertEqual(make_exporter("markdown")(report), "# Plan\n- draft\n\nTag: `tag`\n\nGenerated by report exporter.")
        self.assertEqual(make_exporter("text")(report), "PLAN\ndraft\n[tag]\n-- generated by report exporter --")

    def test_minimal_and_ordered_sections(self):
        self.assertEqual(make_exporter("markdown")(Report("Plan")), "# Plan")
        self.assertEqual(make_exporter("text")(Report("Plan", ["one", "two"])), "PLAN\none\ntwo")

    def test_builder_reuse_preserves_built_snapshot(self):
        builder = ReportBuilder("Plan").add_section("first")
        first = builder.build()
        second = builder.add_section("second").build()
        self.assertEqual(first.sections, ["first"])
        self.assertEqual(second.sections, ["first", "second"])
        first.sections.append("outside")
        self.assertEqual(builder.build().sections, ["first", "second"])

    def test_caller_owned_input_and_independent_defaults(self):
        sections = ["first"]
        first, second = Report("Plan", sections), Report("Other")
        sections.append("outside")
        first.sections.append("inside")
        self.assertEqual(second.sections, [])
        self.assertEqual(first.sections, ["first", "inside"])

    def test_unknown_format_is_value_error_in_both_roles(self):
        for value in ["missing", "Markdown", ""]:
            with self.assertRaises(ValueError): make_exporter(value)
        with self.assertRaises(TypeError): make_exporter(None)

    def test_construction_validation(self):
        with self.assertRaises(ValueError): Report(" ")
        with self.assertRaises(TypeError): Report("Plan", ())
        with self.assertRaises(ValueError): Report("Plan", [" "])
        with self.assertRaises(TypeError): Report("Plan", include_footer=1)
        with self.assertRaises(ValueError): ReportBuilder("Plan").tagged(" ")
        with self.assertRaises(TypeError): ReportBuilder("Plan").add_section(None)

    def test_mutable_report_revalidated_at_export(self):
        report = Report("Plan")
        report.title = " "
        for name in ["markdown", "text"]:
            with self.assertRaises(ValueError): make_exporter(name)(report)
        report.title = "Plan"
        report.sections.append(None)
        for name in ["markdown", "text"]:
            with self.assertRaises(TypeError): make_exporter(name)(report)


if __name__ == "__main__": unittest.main()
